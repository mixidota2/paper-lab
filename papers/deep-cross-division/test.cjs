const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const html = fs.readFileSync(process.argv[2] || __dirname + "/interactive.html", "utf8");
const data = html.match(/<script type="application\/json" id="dcdn-data">([\s\S]+?)<\/script>/);
const script = html.slice(html.indexOf("</section>")).match(/<script>([\s\S]+?)<\/script>/);
assert.ok(data && script, "Provide the built interactive.html or article.");
const nodes = Object.fromEntries([...html.matchAll(/id="(dcdn-[\w-]+)"/g)]
  .map(([, id]) => [id, { disabled:true, addEventListener(name, cb) { this[name] = cb; } }]));
const get = (name) => nodes["dcdn-" + name];
get("data").textContent = data[1];
get("n").valueAsNumber = 5;
get("d").valueAsNumber = 0.005;
get("mask").checked = true;
get("task").value = "view_time";
get("view").value = "reduced";
vm.runInNewContext(script[1], { document:{getElementById:id => nodes[id]} });
const read = (name) => get(name).textContent;
for (const name of ["n","d","mask","task","view"]) assert.equal(get(name).disabled, false);
assert.deepEqual(["product","rho","term","raw","delta"].map(read), ["0.025","100","500","1000","+0.0477"]);
get("d").valueAsNumber = -.005;
get("d").input();
assert.deepEqual(["product","rho","term","raw"].map(read), ["-0.025","-100","-500","-1000"]);
get("mask").checked = false;
get("mask").change();
assert.deepEqual(["product","rho","term","raw"].map(read), ["-0.025","0","0","-1000"]);
get("mask").checked = true;
get("d").valueAsNumber = 0;
get("d").input();
assert.equal(read("term"), "0");
assert.match(read("raw"), /未定義/);
get("d").valueAsNumber = NaN;
get("d").input();
assert.equal(read("product"), "—");
get("d").valueAsNumber = 2;
get("d").input();
assert.deepEqual(["product","rho","term","raw"].map(read), ["10","0.5","2.5","2.5"]);
get("view").value = "deployed";
get("view").change();
assert.equal(read("delta"), "+0.0040");
assert.match(read("view-note"), /結果ではありません/);
get("task").value = "share";
get("task").change();
assert.equal(read("delta"), "+0.0129");
get("view").value = "full";
get("view").change();
assert.equal(read("delta"), "+0.0121");
assert.match(read("treatment-label"), /比率あり/);
console.log("Built DCDN data and event wiring: pass (deterministic DOM stub)");
